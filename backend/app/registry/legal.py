def _stem(word: str) -> str:
    """Грубая основа слова: русские падежные окончания отрезаются по длине.

    Достаточно для подбора по ключевым словам («учителя» → «учител»), полноценная
    морфология тут не нужна и добавила бы зависимость.
    """
    word = word.lower().strip(".,;:!?()«»\"'")
    return word[:-2] if len(word) > 6 else word


def match_prof_standards(text: str, limit: int = 2) -> list[ProfStandard]:
    """Подобрать профстандарты по тексту запроса. Пустой результат — не беда:
    агент тогда задаст вопрос методисту вместо выдумывания кода."""
    haystack = " ".join(_stem(w) for w in text.lower().split())
    scored: list[tuple[int, ProfStandard]] = []
    for std, keywords in _STANDARDS:
        score = sum(
            1
            for kw in keywords
            if all(_stem(part) in haystack for part in kw.split())
        )
        if score:
            scored.append((score, std))
    scored.sort(key=lambda pair: pair[0], reverse=True)
    return [std.model_copy(deep=True) for _, std in scored[:limit]]


def get_prof_standard(code: str) -> ProfStandard | None:
    for std, _ in _STANDARDS:
        if std.code == code:
            return std.model_copy(deep=True)
    return None


def verify_prof_standard(std: ProfStandard) -> ProfStandard:
    """Сверить произвольный профстандарт с реестром.

    Нет в реестре → REJECTED: код мог быть выдуман моделью, в документ не идёт.
    """
    known = get_prof_standard(std.code)
    if known is None:
        std.verification = VerificationStatus.REJECTED
        std.note = (
            f"код {std.code} отсутствует в локальном реестре профстандартов — "
            "проверить в реестре Минтруда перед включением в программу"
        )
        return std
    known.labor_functions = std.labor_functions or known.labor_functions
    return known
